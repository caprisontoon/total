export const findUser = (ch: Channel, uid: string) => ch.users.find((u) => u.uid === uid);

export const won = (n: number) => `${n.toLocaleString('ko-KR')}원`;

/** 후원 금액대 → --chat-don-a~d */
export function donoTier(amount: number): 1 | 2 | 3 | 4 {
  if (amount >= 50000) return 4;
  if (amount >= 10000) return 3;
  if (amount >= 5000) return 2;
  return 1;
}
